import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'
import type { Page, TestInfo } from '@playwright/test'

test.use({ reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } })

async function capture(page: Page, info: TestInfo, name: string) {
  const dismiss = page.getByRole('button', { name: 'Скрыть сообщение', exact: true })
  if (await dismiss.count()) await dismiss.click()
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.locator('html').evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(width)
    const drawer = page.locator('.drawer')
    if (await drawer.count()) expect(await drawer.evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(await drawer.evaluate(element => element.clientWidth))
    await page.screenshot({ path: info.outputPath(`${name}-${width}.png`), fullPage: !(await drawer.count()) })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
}

test('создание, редактирование, повторение и удаление имеют отдельные понятные действия', async ({ page }, info) => {
  test.setTimeout(90_000)
  page.setDefaultTimeout(10_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const title = `Хостинг проекта ${randomUUID().slice(0, 8)}`
  const renamed = `${title} — основной сервер`
  await page.goto('/#payments')
  await page.getByLabel('Логин', { exact: true }).fill(process.env.E2E_ADMIN_USERNAME!)
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить платёж', exact: true }).click()
  // Anonymous /auth/me probes legitimately return 401 before signing in.
  page.on('console', message => { if (message.type() === 'error' || message.type() === 'warning') errors.push(message.text()) })
  const create = page.getByRole('dialog', { name: 'Новый платёж', exact: true })
  await create.getByLabel('Название платежа', { exact: true }).fill(title)
  await create.getByLabel('Сумма', { exact: true }).fill('1250,50')
  await create.getByRole('radio', { name: /Разовый/ }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(create.getByRole('radio', { name: /Ежемесячный/ })).toBeChecked()
  await expect(create.getByRole('button', { name: 'Первый срок оплаты', exact: true })).toBeVisible()
  await expect(create.locator('.payment-schedule-preview time')).toHaveCount(3)
  await capture(page, info, 'create-monthly')
  await create.getByRole('radio', { name: /Разовый/ }).check()
  await expect(create.getByLabel('Сумма', { exact: true })).toHaveValue('1250,50')
  await create.getByRole('button', { name: 'Добавить платёж', exact: true }).click()
  await expect(create).toHaveCount(0)
  let row = page.getByRole('row').filter({ has: page.getByRole('button', { name: title, exact: true }) })
  await expect(row).toContainText('разовый')
  await expect(row.getByRole('button', { name: `Удалить платёж: ${title}`, exact: true })).toBeVisible()
  await row.getByRole('button', { name: `Редактировать платёж: ${title}`, exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Редактировать платёж', exact: true })
  await edit.getByLabel('Название платежа', { exact: true }).fill(renamed)
  await edit.getByLabel('Сумма', { exact: true }).fill('15,25')
  await edit.getByRole('combobox', { name: 'Валюта', exact: true }).click()
  await page.getByRole('option', { name: 'USD', exact: true }).click()
  await edit.getByRole('radio', { name: /Ежемесячный/ }).check()
  await capture(page, info, 'edit-convert')
  await edit.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(edit).toHaveCount(0)
  row = page.getByRole('row').filter({ has: page.getByRole('button', { name: renamed, exact: true }) }).first()
  await expect(row).toContainText('ежемесячный')
  await expect(row).toContainText('15,25')
  await expect(page.locator('.history-chip')).toContainText(renamed)
  await capture(page, info, 'payment-actions')
  await row.getByRole('button', { name: 'Отметить оплату', exact: true }).click()
  const payment = page.getByRole('dialog', { name: 'Отметить оплату', exact: true })
  await expect(payment.getByLabel('Название платежа', { exact: true })).toHaveCount(0)
  await expect(payment.getByRole('button', { name: 'Удалить платёж', exact: true })).toHaveCount(0)
  await capture(page, info, 'confirm-payment')
  await payment.getByRole('button', { name: 'Подтвердить оплату', exact: true }).click()
  await expect(payment).toHaveCount(0)
  await row.getByRole('button', { name: `Редактировать платёж: ${renamed}`, exact: true }).click()
  await expect(edit.getByLabel('Сумма', { exact: true })).toBeDisabled()
  await edit.getByRole('button', { name: 'Отмена', exact: true }).click()
  await row.getByRole('button', { name: renamed, exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Карточка платежа', exact: true })
  await expect(details.getByRole('button', { name: 'Редактировать платёж', exact: true })).toBeVisible()
  await details.getByRole('button', { name: 'Дата и отметка оплаты', exact: true }).click()
  await page.getByRole('button', { name: 'Отменить отметку оплаты', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await row.getByRole('button', { name: `Удалить платёж: ${renamed}`, exact: true }).click()
  const remove = page.getByRole('dialog', { name: 'Удалить платёж?', exact: true })
  await expect(remove).toContainText('Следующие повторения сохранятся')
  await remove.getByRole('button', { name: 'Отмена', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: `Удалить платёж: ${renamed}`, exact: true }).click()
  await remove.getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(remove).toHaveCount(0)
  await expect(row).toHaveCount(0)

  // The main page creates a real monthly rule, and its name can be edited without changing money.
  await page.getByRole('link', { name: 'Платежи', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить платёж', exact: true }).click()
  const monthly = `${title} — подписка`
  await create.getByLabel('Название платежа', { exact: true }).fill(monthly)
  await create.getByLabel('Сумма', { exact: true }).fill('1200')
  await create.getByRole('radio', { name: /Ежемесячный/ }).check()
  await create.getByRole('button', { name: 'Добавить платёж', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: monthly })).toContainText('ежемесячный')
  await page.getByRole('link', { name: 'Регулярные', exact: true }).click()
  await page.getByRole('button', { name: `Редактировать платёж: ${monthly}`, exact: true }).click()
  await edit.getByLabel('Название платежа', { exact: true }).fill(`${monthly} обновлено`)
  await edit.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: `${monthly} обновлено` })).toBeVisible()
  await capture(page, info, 'recurring-actions')
  await page.getByRole('button', { name: `Редактировать платёж: ${monthly} обновлено`, exact: true }).click()
  await page.emulateMedia({ colorScheme: 'dark' })
  await capture(page, info, 'edit-dark')
  await page.keyboard.press('Escape')
  await expect(edit).toHaveCount(0)
  await expect(page.getByRole('button', { name: `Редактировать платёж: ${monthly} обновлено`, exact: true })).toBeFocused()
  expect(errors).toEqual([])
})
